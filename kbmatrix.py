class Matrix:
    def __init__(self, data):
        self.data = data
        self.layout = data.get("layout", "iso")  # physical layout, for the drawings: "iso" or "ansi"
        self.rows = [r["id"] for r in data["rows"]]
        self.columns = [c["id"] for c in data["columns"]]
        self.keys = {k["id"]: k for k in data["keys"]}
        self.order = [k["id"] for k in data["keys"]]
        self.pos = {k["id"]: (k["row"], k["column"]) for k in data["keys"]}
        self.at = {p: k for k, p in self.pos.items()}
        self.unidentified = {(u["row"], u["column"]) for u in data["unidentified"]}
        self.spot_notes = {(u["row"], u["column"]): u["note"] for u in data["unidentified"] if u.get("note")}
        # Keys the keyboard has but whose place in the matrix is not known (the derived US keyboard's ` and \).
        self.unplaced = {k["id"]: k for k in data.get("unplaced", [])}
        self.occupied = set(self.at) | self.unidentified
        self.rollover = data.get("rollover")  # the most keys registered at once (None: no limit known)
        if len(self.at) != len(self.pos):
            raise ValueError("two keys share a spot")
        if self.unidentified & set(self.at):
            raise ValueError("an unidentified spot holds a known key")
        if set(self.unplaced) & set(self.keys):
            raise ValueError("a key is both placed and unplaced")
        # Names, most specific first: ids and labels, then aliases, kVK constants and web codes.
        # Key codes need a prefix ("code:5" is G), since digits are key names.
        named = data["keys"] + data.get("unplaced", [])
        self._names = {}
        for k in named:
            for n in (k["kvk"], k["web_code"]):
                self._names[n.lower()] = k["id"]
        for a, k in ALIASES.items():
            if k in self.keys or k in self.unplaced:
                self._names[a] = k
        for k in named:
            self._names[k["label"].lower()] = k["id"]
            self._names[k["id"].lower()] = k["id"]
        self._codes = {k["keycode"]: k["id"] for k in named}

    # Names

    def key(self, token):
        """Key id for a name or label ("J", "5", ";", "semicolon"), a kVK_ constant, a web KeyboardEvent.code
        ("KeyJ"), or a macOS key code written "code:38"."""
        t = str(token)
        if t in self.keys:
            return t
        if t.lower().startswith("code:"):
            k = self._codes.get(int(t[5:]))
        else:
            k = self._names.get(t.lower()) or self._names.get(t)
        if k in self.unplaced:
            u = self.unplaced[k]
            raise KeyError(f"{u['label']} is not placed in this keyboard's matrix: {u['note']}")
        if k is None:
            raise KeyError(f"unknown key {token!r} (try: python3 kbmatrix.py keys)")
        return k

    def keys_of(self, tokens):
        """Key ids for a list of names; a name may also be several names joined with spaces or '+'."""
        out = []
        for t in tokens:
            parts = [t] if t in self.keys or t.lower() in self._names else t.replace("+", " ").split()
            for part in parts:
                k = self.key(part)
                if k not in out:
                    out.append(k)
        return out

    def label(self, k):
        return self.keys[k]["label"]

    # The rule

    def shares(self, a, b):
        (ra, ca), (rb, cb) = self.pos[a], self.pos[b]
        return ra == rb or ca == cb

    def l_shape(self, a, b, c):
        """(corner key, fourth-corner spot) if the three keys form an L, else None."""
        for x, y, z in ((a, b, c), (b, a, c), (c, a, b)):
            if self.shares(y, z):
                continue
            (rx, cx), (ry, cy), (rz, cz) = self.pos[x], self.pos[y], self.pos[z]
            if rx == ry and cx == cz:
                return x, (rz, cy)
            if cx == cy and rx == rz:
                return x, (ry, cz)
        return None

    def triple_blocked(self, a, b, c):
        s = self.l_shape(a, b, c)
        return s is not None and s[1] in self.occupied

    def blocked_triples(self, keys):
        """Every 3-key part of `keys` the keyboard drops, as (triple, corner, fourth spot)."""
        keys = self.keys_of(keys)
        out = []
        for t in itertools.combinations(keys, 3):
            s = self.l_shape(*t)
            if s and s[1] in self.occupied:
                out.append((t, s[0], s[1]))
        return out

    def too_many(self, keys):
        return self.rollover is not None and len(keys) > self.rollover

    def registers(self, keys):
        keys = self.keys_of(keys)
        return not self.too_many(keys) and not self.blocked_triples(keys)

    def occupant(self, spot):
        if spot in self.at:
            return self.label(self.at[spot])
        if spot in self.spot_notes:
            return f"an unknown key ({self.spot_notes[spot]})"
        if spot in self.unidentified:
            return "an unidentified key (not a letter, digit, punctuation or space key)"
        return None

    def explain(self, keys):
        keys = self.keys_of(keys)
        names = " + ".join(self.label(k) for k in keys)
        bad = self.blocked_triples(keys)
        if len(keys) < 3:
            return f"{names}: registers (any one or two keys always do)."
        if self.too_many(keys):
            return f"{names}: dropped: the keyboard registers at most {self.rollover} keys at once."
        if not bad:
            ls = [t for t in itertools.combinations(keys, 3) if self.l_shape(*t)]
            text = f"{names}: registers."
            for t in ls:
                corner, spot = self.l_shape(*t)
                text += (f"\n  {'+'.join(self.label(x) for x in t)} is an L (corner {self.label(corner)}), but the "
                         f"fourth corner (row {spot[0]}, column {spot[1]}) is an empty spot.")
            return text
        text = f"{names}: dropped by the keyboard ({len(bad)} bad 3-key part{'s' if len(bad) > 1 else ''})."
        for t, corner, spot in bad:
            others = [x for x in t if x != corner]
            rc = self.pos[corner]
            row_mate = next(x for x in others if self.pos[x][0] == rc[0])
            col_mate = next(x for x in others if self.pos[x][1] == rc[1])
            text += (f"\n  {self.label(corner)} shares row '{rc[0]}' with {self.label(row_mate)} and column "
                     f"'{rc[1]}' with {self.label(col_mate)}; the fourth corner (row {spot[0]}, column {spot[1]}) "
                     f"holds {self.occupant(spot)}.")
        return text

    def dropped_when_holding(self, a, b):
        a, b = self.key(a), self.key(b)
        return [x for x in self.order if x not in (a, b) and self.triple_blocked(a, b, x)]

    def all_blocked_triples(self):
        out = []
        for t in itertools.combinations(self.order, 3):
            s = self.l_shape(*t)
            if s and s[1] in self.occupied:
                out.append((t, s[0], s[1]))
        return out

    def never_blocking(self):
        """Keys that are not part of any dropped 3-key combination."""
        used = set()
        for t, _, _ in self.all_blocked_triples():
            used.update(t)
        return [k for k in self.order if k not in used]

    def spot_states(self, observations):
        """For every spot: 'key', 'unidentified', 'empty' (seen empty as a fourth corner) or 'unknown'."""
        seen_empty = set()
        for ob in observations:
            if ob.blocked:
                continue
            for t in itertools.combinations(ob.keys, 3):
                s = self.l_shape(*t)
                if s and s[1] not in self.occupied:
                    seen_empty.add(s[1])
        out = {}
        for r in self.rows:
            for c in self.columns:
                p = (r, c)
                out[p] = ("key" if p in self.at else "unidentified" if p in self.unidentified
                          else "empty" if p in seen_empty else "unknown")
        return out

    def open_spots(self, observations):
        """Unknown spots that decide whether some combination of known keys registers."""
        states = self.spot_states(observations)
        need = set()
        for t in itertools.combinations(self.order, 3):
            s = self.l_shape(*t)
            if s and states[s[1]] == "unknown":
                need.add(s[1])
        return sorted(need)


def load(path=DEFAULT_DATA):
    with open(path, encoding="utf-8") as f:
        return Matrix(json.load(f))


# The US (ANSI) keyboard --------------------------------------------------------------------------------------

# The two mapped keys that are somewhere else on an ANSI keyboard, and where.
ANSI_MOVED = {
    "Grave": "on US keyboards ` is left of 1, where ISO keyboards have §, and its wires were not measured",
    "Backslash": "on US keyboards \\ is above Return, where ISO keyboards have the top of Return, and its wires were "
                 "not measured",
}
ANSI_ROWS = {
    "space": "Space and ' (ISO keyboards also have ` here); the unidentified keys here are probably modifiers",
    "bracket": "[ and ] (ISO keyboards also have \\ here)",
}


def derive_ansi(iso):
    """The US (ANSI) keyboard of the same model, derived from the measured ISO data. Not measured: the 46 keys
    that are in the same place on both layouts keep their ISO wires; ` and \\, which are elsewhere on ANSI
    keyboards, are left unplaced; the spots of the ISO ` and \\ keys still count as keys, so every combination
    of the other keys that the ISO keyboard drops is predicted to drop here too."""
    moved = [k for k in iso["keys"] if k["id"] in ANSI_MOVED]
    spots = [{"row": k["row"], "column": k["column"],
              "note": f"ISO keyboards have {k['label']} here; not measured on US keyboards, so counted as a key"}
             for k in moved]
    rank = {r["id"]: i for i, r in enumerate(iso["rows"])}, {c["id"]: i for i, c in enumerate(iso["columns"])}
    device = {k: v for k, v in iso["device"].items() if k != "measured"}
    device["keyboard"] = "built-in, US (ANSI); not measured, derived from the ISO measurement of the same model"
    return {
        "schema": iso["schema"],
        "layout": "ansi",
        "device": device,
        "derived_from": os.path.basename(DEFAULT_DATA),
        "basis": ("Not measured. This is the ISO wiring, assuming that the 46 keys in the same place on both layouts "
                  "keep their wires. ` and \\ are elsewhere on US keyboards, so they are left out (see unplaced). "
                  "The spots of the ISO ` and \\ keys still count as keys (see unidentified), so every combination "
                  "of the other keys that the ISO keyboard drops is predicted to drop here too."),
        "rule": iso["rule"],
        "rollover": iso["rollover"],
        "columns": iso["columns"],
        "rows": [dict(r, description=ANSI_ROWS.get(r["id"], r["description"])) for r in iso["rows"]],
        "keys": [k for k in iso["keys"] if k["id"] not in ANSI_MOVED],
        "unplaced": [{"id": k["id"], "label": k["label"], "keycode": k["keycode"], "kvk": k["kvk"],
                      "web_code": k["web_code"], "note": ANSI_MOVED[k["id"]]} for k in moved],
        "unidentified": sorted(iso["unidentified"] + spots, key=lambda u: (rank[0][u["row"]], rank[1][u["column"]])),
    }


# Observations -------------------------------------------------------------------------------------------------

class Observation:
    def __init__(self, keys, blocked, label, source):
        self.keys = keys
        self.blocked = blocked
        self.label = label
        self.source = source


def parse_observations(path, kb):
    """Reads a Matrix Scan / Wiring Check report: one observation per tapped key, one per combination."""
    name = os.path.basename(path)
    all_keys = None
    out = []
    with open(path, encoding="utf-8") as f:
        for line in f:
            fields = line.split("#", 1)[0].split()
            if not fields:
                continue
            head = fields[0]
            if head == "keys":
                all_keys = [kb.key(x) for x in fields[1:]]
            elif head == "sweep":
                a, b = [kb.key(x) for x in fields[1].split("+")]
                rest = fields[3:]
                split = next((i for i, x in enumerate(rest) if x in ("untested", "tapped")), len(rest))
                blocked = set() if rest[:split] == ["-"] else {kb.key(x) for x in rest[:split]}
                if split < len(rest):
                    listed = [kb.key(x) for x in rest[split + 1:]]
                    tapped = listed if rest[split] == "tapped" else [k for k in all_keys if k not in listed and k not in (a, b)]
                else:
                    tapped = [k for k in all_keys if k not in (a, b)]
                for x in tapped:
                    out.append(Observation([a, b, x], x in blocked,
                                           f"hold {kb.label(a)}+{kb.label(b)}, tap {kb.label(x)}", name))
            elif head == "combo":
                ks = [kb.key(x) for x in fields[1].split("+")]
                out.append(Observation(ks, fields[2] == "fail", "press " + "+".join(kb.label(k) for k in ks), name))
    return out


def all_observations(kb, files=None):
    files = files or (FITTED + PREDICTED)
    obs = []
    for f in files:
        obs += parse_observations(os.path.join(OBSERVATIONS, f), kb)
    return obs


def validate(kb, files=None):
    """(explained, total, mismatches) for the given observation files."""
    obs = all_observations(kb, files)
    bad = [o for o in obs if kb.registers(o.keys) == o.blocked]
    return len(obs) - len(bad), len(obs), bad


# Physical keyboards (ISO and US ANSI), in key units -----------------------------------------------------------

def _keyboard(middle):
    """(label, x, y, w, h, key id or None) for every key: the function row, the rows `middle` adds, the bottom row."""
    k = []

    def add(label, x, y, w=1.0, h=1.0, kid=None):
        k.append((label, x, y, w, h, kid))

    def row(y, x0, items):
        for i, (label, kid) in enumerate(items):
            add(label, x0 + i, y, kid=kid)

    add("esc", 0, 0, 1.5, 0.6)
    for i in range(12):
        add(f"F{i + 1}", 1.5 + i, 0, 1, 0.6)
    add("Touch ID", 13.5, 0, 1, 0.6)
    middle(add, row)
    add("fn", 0, 4.7)
    add("control", 1, 4.7)
    add("option", 2, 4.7)
    add("command", 3, 4.7, 1.25)
    add("space", 4.25, 4.7, 5, kid="Space")
    add("command", 9.25, 4.7, 1.25)
    add("option", 10.5, 4.7)
    add("←", 11.5, 4.7)
    add("↑", 12.5, 4.7, 1, 0.5)
    add("↓", 12.5, 5.2, 1, 0.5)
    add("→", 13.5, 4.7)
    return k


def iso_keyboard():
    """(label, x, y, w, h, key id or None). The ISO Return key is drawn separately (RETURN_PATH)."""
    def middle(add, row):
        row(0.7, 0, [("§", None)] + [(d, d) for d in "1234567890"] + [("-", "Minus"), ("=", "Equal")])
        add("delete", 13, 0.7, 1.5)
        add("tab", 0, 1.7, 1.5)
        row(1.7, 1.5, [(c, c) for c in "QWERTYUIOP"] + [("[", "LBracket"), ("]", "RBracket")])
        add("caps lock", 0, 2.7, 1.75)
        row(2.7, 1.75, [(c, c) for c in "ASDFGHJKL"] + [(";", "Semicolon"), ("'", "Quote"), ("\\", "Backslash")])
        add("shift", 0, 3.7, 1.25)
        row(3.7, 1.25, [("`", "Grave")] + [(c, c) for c in "ZXCVBNM"] + [(",", "Comma"), (".", "Period"), ("/", "Slash")])
        add("shift", 12.25, 3.7, 2.25)
    return _keyboard(middle)


def ansi_keyboard():
    """(label, x, y, w, h, key id or None). ` is left of 1, \\ above Return, Return one row tall, a wide left
    Shift and no key between it and Z."""
    def middle(add, row):
        row(0.7, 0, [("`", "Grave")] + [(d, d) for d in "1234567890"] + [("-", "Minus"), ("=", "Equal")])
        add("delete", 13, 0.7, 1.5)
        add("tab", 0, 1.7, 1.5)
        row(1.7, 1.5, [(c, c) for c in "QWERTYUIOP"] + [("[", "LBracket"), ("]", "RBracket"), ("\\", "Backslash")])
        add("caps lock", 0, 2.7, 1.75)
        row(2.7, 1.75, [(c, c) for c in "ASDFGHJKL"] + [(";", "Semicolon"), ("'", "Quote")])
        add("return", 12.75, 2.7, 1.75)
        add("shift", 0, 3.7, 2.25)
        row(3.7, 2.25, [(c, c) for c in "ZXCVBNM"] + [(",", "Comma"), (".", "Period"), ("/", "Slash")])
        add("shift", 12.25, 3.7, 2.25)
    return _keyboard(middle)


def keyboard_geometry(layout):
    return ansi_keyboard() if layout == "ansi" else iso_keyboard()


KB_W, KB_H = 14.5, 5.7
RETURN_PATH = [(13.5, 1.7), (14.5, 1.7), (14.5, 3.7), (13.75, 3.7), (13.75, 2.7), (13.5, 2.7)]


def return_path(layout):
    """Outline of the L-shaped ISO Return key; None on ANSI, where Return is an ordinary key."""
    return None if layout == "ansi" else RETURN_PATH

